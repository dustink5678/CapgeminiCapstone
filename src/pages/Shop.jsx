import { useEffect, useMemo, useRef, useState } from "react";
import { useSearchParams } from "react-router-dom";
import { fetchJson } from "../api";
import ProductCard from "../components/ProductCard";
import Rail from "../components/Rail";
import { queueEvent } from "../session";

/** Module-level guards survive React StrictMode remounts — one auto personalize per tab. */
const AUTO_PERSONALIZE_KEY = "spark.autoPersonalize";
let autoPersonalizeInFlight = false;

function claimAutoPersonalize() {
  if (autoPersonalizeInFlight) return false;
  if (sessionStorage.getItem(AUTO_PERSONALIZE_KEY) === "1") return false;
  autoPersonalizeInFlight = true;
  sessionStorage.setItem(AUTO_PERSONALIZE_KEY, "1");
  return true;
}

export function clearAutoPersonalizeGuard() {
  autoPersonalizeInFlight = false;
  sessionStorage.removeItem(AUTO_PERSONALIZE_KEY);
}

export default function Shop({ cart, add, setQty }) {
  const [params, setParams] = useSearchParams();
  const [items, setItems] = useState([]);
  const [error, setError] = useState("");
  const [agentStatus, setAgentStatus] = useState("");
  const [busy, setBusy] = useState(false);
  const [market, setMarket] = useState(null);
  const stormRef = useRef(null);

  useEffect(() => {
    // Read-only: the region brief is generated by the market-context agent, never from Shop.
    fetchJson("/api/market-context?storeId=4127")
      .then((data) => setMarket(data.storeRegion?.marketBrief || null))
      .catch(() => {});
  }, []);

  async function loadCatalog() {
    const catalog = await fetchJson("/api/catalog");
    setItems(catalog);
    return catalog;
  }

  async function runPersonalize(force = false) {
    setBusy(true);
    setAgentStatus(force ? "Refreshing picks…" : "Generating picks…");
    try {
      const result = await fetchJson("/api/agents/personalize", {
        method: "POST",
        body: JSON.stringify({ force }),
      });
      await loadCatalog();
      if (result.skipped) {
        setAgentStatus(result.reason === "cache_fresh" ? "Using cached picks" : `Skipped (${result.reason})`);
      } else if (result.usedGemini || result.mode === "mock") {
        setAgentStatus(result.mode === "mock" || result.metrics?.model?.includes("mock")
          ? "Picks updated (mock model)"
          : "Picks updated with Gemini");
      } else {
        setAgentStatus("Picks updated (fallback reasons)");
      }
    } catch (err) {
      setAgentStatus(err.message);
    } finally {
      setBusy(false);
      autoPersonalizeInFlight = false;
    }
  }

  useEffect(() => {
    loadCatalog()
      .then((catalog) => {
        const hasRecs = catalog.some((item) => item.recommendation);
        if (!hasRecs && claimAutoPersonalize()) {
          // First visit with empty cache only — not on every GET / remount.
          return runPersonalize(false);
        }
        return null;
      })
      .catch((err) => setError(err.message));
  }, []);

  useEffect(() => {
    const query = (params.get("q") || "").trim();
    if (query) queueEvent({ type: "search", query, source: "home" });
  }, [params]);

  const qtyById = useMemo(() => Object.fromEntries(cart.lines.map((line) => [line.id, line.qty])), [cart]);
  const query = (params.get("q") || "").trim().toLowerCase();

  const recommended = items.filter((item) => item.recommendation).sort((a, b) => a.recommendation.rank - b.recommendation.rank);
  const storm = items.filter((item) => item.shelf === "storm" && !item.recommendation);
  const staples = items.filter((item) => item.shelf === "staples" && !item.recommendation);
  const activeTags = new Set(market?.activeTags || []);
  const seasonal = items
    .filter((item) => item.shelf === "seasonal" && !item.recommendation)
    .map((item) => ({ item, hits: (item.tags || []).filter((tag) => activeTags.has(tag)).length }))
    .filter(({ hits }) => !activeTags.size || hits > 0)
    .sort((a, b) => b.hits - a.hits)
    .map(({ item }) => item);
  const results = query
    ? items.filter((item) => `${item.name} ${item.aisle} ${(item.tags || []).join(" ")}`.toLowerCase().includes(query))
    : [];

  const cardProps = (item, { trackView = false } = {}) => ({
    item,
    qty: qtyById[item.id] || 0,
    onAdd: add,
    onQty: setQty,
    onView: trackView
      ? () =>
          queueEvent({
            type: "product_view",
            productId: item.id,
            dwellMs: 4200,
            source: item.recommendation ? "for_you" : "home",
          })
      : undefined,
  });

  if (error) return <main className="wm-page"><p className="notice error">{error}</p></main>;

  return (
    <main className="wm-page">
      {query ? (
        <section className="shelf">
          <div className="shelf-head">
            <div>
              <h2>Results for “{params.get("q")}”</h2>
              <p>{results.length} items at Columbia Garners Ferry Rd Supercenter</p>
            </div>
            <button className="link-btn" onClick={() => setParams({})}>
              Clear search
            </button>
          </div>
          <div className="pgrid six">
            {results.map((item) => (
              <ProductCard key={item.id} {...cardProps(item)} />
            ))}
          </div>
          {results.length === 0 && <p className="empty">No items match that search.</p>}
        </section>
      ) : (
        <>
          <section className="hero">
            <div className="hero-copy">
              <p className="hero-kicker">Hurricane alert · Richland County</p>
              <h1>Hurricane Rose is on the way. Stock up before Friday.</h1>
              <p>Strong winds and heavy rain are expected Friday afternoon. Pickup times at Columbia Garners Ferry Rd are filling quickly.</p>
              <button className="pill-btn" onClick={() => stormRef.current?.scrollIntoView({ behavior: "smooth" })}>
                Shop storm prep
              </button>
            </div>
            <div className="hero-art">
              {["water", "milk", "eggs", "batteries"].map((id) => (
                <img key={id} src={`/products/${id}.jpg`} alt="" />
              ))}
            </div>
          </section>

          <section className="shelf">
            <div className="shelf-head">
              <div>
                <h2>Picked for you, Doug</h2>
                <p>Based on your recent activity and the hurricane warning in your area.</p>
                {agentStatus && <p className="muted agent-status">{agentStatus}</p>}
              </div>
              <button className="link-btn" disabled={busy} onClick={() => runPersonalize(true)}>
                {busy ? "Working…" : "Refresh picks"}
              </button>
            </div>
            <div className="pgrid four">
              {recommended.map((item) => (
                <ProductCard
                  key={item.id}
                  {...cardProps(item, { trackView: true })}
                  whyLabel={item.recommendation.label}
                  why={item.recommendation.reason}
                />
              ))}
            </div>
            {recommended.length === 0 && !busy && (
              <p className="empty">No cached picks yet. Click Refresh picks to run the personalization agent once.</p>
            )}
          </section>

          <section className="shelf" ref={stormRef}>
            <div className="shelf-head">
              <div>
                <h2>Storm prep essentials</h2>
                <p>Get it before the hurricane hits. Pickup today or delivery in as soon as 1 hour.</p>
              </div>
              <span className="link-btn">View all</span>
            </div>
            <Rail className="six">
              {storm.map((item) => (
                <div key={item.id} className="rail-item">
                  <ProductCard {...cardProps(item)} />
                </div>
              ))}
            </Rail>
          </section>

          {seasonal.length > 0 && (
            <section className="shelf">
              <div className="shelf-head">
                <div>
                  <h2>
                    {market?.calendar?.length ? `Get ready for ${market.calendar[0].label}` : "Seasonal and holiday picks"}
                  </h2>
                  <p>
                    {market?.calendar?.length
                      ? market.calendar.map((c) => (c.daysUntil === 0 ? `${c.label} is today` : `${c.label} in ${c.daysUntil} days`)).join(" · ")
                      : "What’s in season around Columbia this week."}
                  </p>
                </div>
                <span className="link-btn">View all</span>
              </div>
              <Rail className="six">
                {seasonal.map((item) => (
                  <div key={item.id} className="rail-item">
                    <ProductCard {...cardProps(item)} />
                  </div>
                ))}
              </Rail>
            </section>
          )}

          <section className="shelf">
            <div className="shelf-head">
              <div>
                <h2>Everyday grocery essentials</h2>
                <p>Low prices on the basics, every day.</p>
              </div>
              <span className="link-btn">View all</span>
            </div>
            <Rail className="six">
              {staples.map((item) => (
                <div key={item.id} className="rail-item">
                  <ProductCard {...cardProps(item)} />
                </div>
              ))}
            </Rail>
          </section>
        </>
      )}
    </main>
  );
}
